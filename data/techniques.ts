export const getRandomTechnique = (): Technique => {
    return techniques[Math.floor(Math.random() * techniques.length)];
};

export const getTechniquesByCategory = (category: string): Technique[] => {
    if (category === 'All') return techniques;
    return techniques.filter(t => t.category === category);
};

export const getTechniqueById = (id: number): Technique | undefined => {
    return techniques.find(t => t.id === id);
};
